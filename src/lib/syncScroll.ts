import { useEffect } from "react";

/**
 * Keep two scroll containers in sync (vertical proportionally, horizontal 1:1).
 * Works in both side-by-side and stacked layouts.
 */
export function useSyncedScroll(left: HTMLElement | null, right: HTMLElement | null, enabled: boolean): void {
  useEffect(() => {
    if (!enabled || !left || !right) return;
    return connectSyncedScroll(left, right);
  }, [left, right, enabled]);
}

export function connectSyncedScroll(left: HTMLElement, right: HTMLElement): () => void {
  const expected = new Map<HTMLElement, { top: number; left: number }>();
  const sync = (from: HTMLElement, to: HTMLElement) => {
    const written = expected.get(from);
    // Suppress only the event generated by our last write, then accept user scrolling again.
    expected.delete(from);
    if (written && Math.abs(written.top - from.scrollTop) <= 1 && Math.abs(written.left - from.scrollLeft) <= 1) return;
    const sourceMax = from.scrollHeight - from.clientHeight;
    const targetMax = to.scrollHeight - to.clientHeight;
    const top = sourceMax > 0 && targetMax > 0 ? Math.round((from.scrollTop / sourceMax) * targetMax) : 0;
    if (to.scrollTop === top && to.scrollLeft === from.scrollLeft) return;
    to.scrollTop = top;
    to.scrollLeft = from.scrollLeft;
    expected.set(to, { top: to.scrollTop, left: to.scrollLeft });
  };
  const onLeft = () => sync(left, right);
  const onRight = () => sync(right, left);
  left.addEventListener("scroll", onLeft, { passive: true });
  right.addEventListener("scroll", onRight, { passive: true });
  return () => {
    left.removeEventListener("scroll", onLeft);
    right.removeEventListener("scroll", onRight);
  };
}
